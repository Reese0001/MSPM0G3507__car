static bool send_command(uint8_t command)
{
    uint8_t message[2];

    message[0] = SSD1306_CONTROL_COMMAND;
    message[1] = command;
    return BSP_OledI2C_Write(SSD1306_ADDRESS_7BIT, message, 2U);
}

bool Ssd1306_Init(void)
{
    static const uint8_t init_sequence[] = {
        0xAEU,        /* display off */
        0xD5U, 0x80U, /* clock divide */
        0xA8U, 0x3FU, /* multiplex 64 */
        0xD3U, 0x00U, /* display offset */
        0x40U,        /* start line 0 */
        0x8DU, 0x14U, /* charge pump on */
        0x20U, 0x02U, /* page addressing mode */
        0xA1U,        /* segment remap */
        0xC8U,        /* COM scan direction */
        0xDAU, 0x12U, /* COM pins */
        0x81U, 0xCFU, /* contrast */
        0xD9U, 0xF1U, /* precharge */
        0xDBU, 0x40U, /* VCOM detect */
        0xA4U,        /* resume from RAM */
        0xA6U,        /* normal polarity */
        0xAFU         /* display on */
    };
    uint32_t index;

    BSP_OledI2C_Init();
    display_present = true;
    for (index = 0U; index < sizeof(init_sequence); index++) {
        if (!send_command(init_sequence[index])) {
            display_present = false;
            return false;
        }
    }
    Ssd1306_ClearBuffer();
    dirty_pages = 0xFFU;
    return Ssd1306_FlushDirty();
}

bool Ssd1306_WritePage(uint8_t page, const uint8_t data[128])
{
    static uint8_t message[1U + SSD1306_WIDTH];

    if (page >= SSD1306_PAGES || data == 0) {
        return false;
    }
    if (!send_command((uint8_t)(0xB0U | page)) ||
        !send_command(0x00U) || !send_command(0x10U)) {
        return false;
    }
    message[0] = SSD1306_CONTROL_DATA;
    (void)memcpy(&message[1], data, SSD1306_WIDTH);
    return BSP_OledI2C_Write(SSD1306_ADDRESS_7BIT, message,
                             (uint16_t)sizeof(message));
}

void Ssd1306_ClearBuffer(void)
{
    (void)memset(framebuffer, 0, sizeof(framebuffer));
    dirty_pages = 0xFFU;
}

void Ssd1306_DrawText(uint8_t page, uint8_t column, const char *text)
{
    uint32_t x;

    if (page >= SSD1306_PAGES || text == 0) {
        return;
    }
    x = (uint32_t)column * SSD1306_CELL_WIDTH;
    for (; *text != '\0'; text++) {
        const uint8_t *glyph;
        uint8_t glyph_column;
        char character = *text;

        if (character < ' ' || character > '~') {
            character = '?';
        }
        if (x + SSD1306_CELL_WIDTH > SSD1306_WIDTH) {
            break;
        }
        glyph = font5x7[character - ' '];
        for (glyph_column = 0U; glyph_column < SSD1306_FONT_WIDTH;
             glyph_column++) {
            framebuffer[page][x + glyph_column] = glyph[glyph_column];
        }
        framebuffer[page][x + SSD1306_FONT_WIDTH] = 0x00U;
        x += SSD1306_CELL_WIDTH;
    }
    dirty_pages |= (uint8_t)(1U << page);
}

bool Ssd1306_FlushDirty(void)
{
    uint8_t page;

    if (!display_present) {
        return false;
    }
    for (page = 0U; page < SSD1306_PAGES; page++) {
        if ((dirty_pages & (uint8_t)(1U << page)) == 0U) {
            continue;
        }
        if (!Ssd1306_WritePage(page, framebuffer[page])) {
            return false;
        }
        dirty_pages &= (uint8_t)~(1U << page);
    }
    return true;
}
